using System.ComponentModel.DataAnnotations;
using IDCard.Domain.Entities;
using IDCard.Domain.Enums;

namespace IDCard.Web.Models;

/// <summary>
/// PLAN-38 (PLAN-37 defect 2): what the issue/edit forms post. The forms used to bind the <see cref="IssuedCard"/> entity,
/// whose non-nullable <c>CardDesign</c> navigation MVC treats as implicitly required (and whose serial number is
/// required although the server generates it, COD-001), so <c>IssuedCards/Create</c> could never succeed.
/// </summary>
public sealed class IssuedCardFormModel
{
    public Guid Id { get; set; }

    [Required(ErrorMessage = "اختر الموظف")]
    [Display(Name = "الموظف")]
    public Guid? EmployeeId { get; set; }

    [Required(ErrorMessage = "اختر التصميم")]
    [Display(Name = "التصميم")]
    public Guid? CardDesignId { get; set; }

    [Display(Name = "تاريخ الإصدار")]
    public DateTime IssuedAt { get; set; } = DateTime.UtcNow;

    [Display(Name = "تاريخ الانتهاء")]
    public DateOnly? ExpiresAt { get; set; }

    [Display(Name = "الحالة")]
    public CardStatus Status { get; set; } = CardStatus.Active;

    /// <summary>Shown only; generated by HR.Core on issue and immutable afterwards (COD-001).</summary>
    [Display(Name = "الرقم التسلسلي")]
    public string? SerialNumber { get; set; }

    public static IssuedCardFormModel From(IssuedCard card) => new()
    {
        Id = card.Id,
        EmployeeId = card.EmployeeId,
        CardDesignId = card.CardDesignId,
        IssuedAt = card.IssuedAt,
        ExpiresAt = card.ExpiresAt,
        Status = card.Status,
        SerialNumber = card.SerialNumber,
    };
}
