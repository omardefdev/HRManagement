    public static (string First, string? Middle, string Last, bool IsFemale) BuildPerson(int index)
    {
        var isFemale = index % 5 is 1 or 3; // ~40% female
        var firstNames = isFemale ? FemaleFirstNames : MaleFirstNames;
        var first = firstNames[index % firstNames.Length];
        var middle = firstNames[(index * 3 + 7) % firstNames.Length];
        var last = FamilyNames[index % FamilyNames.Length];
        // Occasionally omit middle name for variety
        var useMiddle = index % 4 != 0;
        return (first, useMiddle ? middle : null, last, isFemale);
    }

    public static string FullName(string first, string? middle, string last) =>
        middle is null ? $"{first} {last}" : $"{first} {middle} {last}";

    public static string NationalId(int index) => $"0101{(index + 1):D7}";

    public static string Phone(int index) => $"09{(10000000 + index * 137) % 100000000:D8}";

    public static string Email(string first, string last, int index)
    {
        var local = $"emp{index:D3}";
        return $"{local}@hr-demo.gov.sy";
    }

    public static string Address(int index)
    {
        var street = Streets[index % Streets.Length];
        var city = Cities[index % Cities.Length];
        var building = (index % 200) + 1;
        return $"{street}، بناء رقم {building}، {city}";
    }

    public static string JobTitle(int index) => JobTitles[Math.Min(index, JobTitles.Length - 1) % JobTitles.Length];

    public static string Governorate(int index) => Governorates[index % Governorates.Length];
