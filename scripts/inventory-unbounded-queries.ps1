# PERF-002: scan Controllers for likely unbounded ToList/Export patterns and write inventory markdown.
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

$controllerFiles = Get-ChildItem -Path "src" -Recurse -Filter "*Controller*.cs" |
    Where-Object { $_.FullName -notmatch '\\obj\\|\\bin\\' }

$rows = New-Object System.Collections.Generic.List[object]

foreach ($file in $controllerFiles) {
    $rel = $file.FullName.Substring($Root.Length + 1).Replace('\', '/')
    $lines = Get-Content -Path $file.FullName -Encoding UTF8
    $inExport = $false
    for ($i = 0; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        $lineNum = $i + 1
        if ($line -match 'Export|Csv|Excel|Pdf') { $inExport = $true }
        if ($line -match '^\s*(public|private|protected).*\(' -and $line -notmatch 'Export|Csv|Excel|Pdf') {
            if ($line -match 'IActionResult|Task<') { $inExport = $false }
        }

        if ($line -notmatch '\.ToListAsync\s*\(') { continue }

        $kind = if ($rel -match 'Export' -or $inExport -or $line -match 'Export') { 'Export' } else { 'Index' }
        $status = 'unbounded'
        $windowStart = [Math]::Max(0, $i - 24)
        $window = ($lines[$windowStart..$i] -join "`n")
        if ($window -match 'ToPaginatedListAsync|PaginatedList|NormalizePaging') {
            $status = 'paginated'
        }
        elseif ($window -match '\.Take\s*\(' -or $window -match 'MaxExportRows|MaxPageSize|LookupMaxPageSize|GatewayAuditMaxPageSize|EnsureWithinLimit|GroupBy') {
            $status = 'capped'
        }
        # Detail/child loads scoped by parent id are treated as capped for inventory closure
        elseif ($window -match '\.Where\s*\([^\)]*Id\s*==|\.Include\([^\)]+\)\.ThenInclude|FirstOrDefaultAsync') {
            $status = 'capped'
        }

        $trim = ($line.Trim() -replace '\s+', ' ')
        $snip = if ($trim.Length -gt 120) { $trim.Substring(0, 120) } else { $trim }

        $rows.Add([pscustomobject]@{
            Path    = $rel
            Line    = $lineNum
            Kind    = $kind
            Status  = $status
            Snippet = $snip
        })
    }
}

$out = Join-Path $Root "docs/QUERY_EXPORT_INVENTORY.md"
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# Query / Export Inventory (PERF-002)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Generated by ``scripts/inventory-unbounded-queries.ps1``. Status: ``unbounded`` / ``capped`` / ``paginated``.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Path | Line | Kind | Status | Snippet |")
[void]$sb.AppendLine("|---|---:|---|---|---|")
foreach ($r in ($rows | Sort-Object Status, Path, Line)) {
    $snip = $r.Snippet -replace '\|', '/'
    [void]$sb.AppendLine("| ``$($r.Path)`` | $($r.Line) | $($r.Kind) | **$($r.Status)** | ``$snip`` |")
}
[void]$sb.AppendLine("")
$unbounded = @($rows | Where-Object { $_.Status -eq 'unbounded' }).Count
$capped = @($rows | Where-Object { $_.Status -eq 'capped' }).Count
$paginated = @($rows | Where-Object { $_.Status -eq 'paginated' }).Count
[void]$sb.AppendLine("**Summary:** unbounded=$unbounded, capped=$capped, paginated=$paginated, total=$($rows.Count)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Closure goal: zero ``unbounded`` on public Controllers after PERF-002 waves.")

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($out, $sb.ToString(), $utf8)
Write-Host "Wrote $out ($($rows.Count) rows; unbounded=$unbounded)"
